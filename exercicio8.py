Lista = [5, 7, 2, 9, 4, 1, 3]
print("O tamanho da lista é:{} ". format(len(Lista)))
print("O maior valor da lista  da lista é:{} ".format(max(Lista)))
print("O menor valor da lista  da lista é:{} ".format(min(Lista)))
print("A soma de todos os elementos da lista é:{} ".format(sum(Lista)))
print("A lista em ordem crescente é:{} ".format(sorted(Lista)))
print("A lista em ordem decrescente é:{} ". format(sorted(Lista, reverse=True)))